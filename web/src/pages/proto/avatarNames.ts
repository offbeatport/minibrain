function pick<T>(items: readonly T[], value: number): T {
    return items[value % items.length];
}

function randomPair(): string {
    const [first, second] = crypto.getRandomValues(new Uint32Array(2));
    const adjective = pick(ADJECTIVES, first);
    const noun = pick(NOUNS, second);
    return adjective === noun ? randomPair() : `${adjective} ${noun}`;
}

const ATTEMPTS = 40;

export function generateName(taken: Iterable<string> = []): string {
    const used = new Set(Array.from(taken, (name) => name.trim().toLowerCase()));
    for (let attempt = 0; attempt < ATTEMPTS; attempt++) {
        const name = randomPair();
        if (!used.has(name.toLowerCase())) {
            return name;
        }
    }
    return randomPair();
}
